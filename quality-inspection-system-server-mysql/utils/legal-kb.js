/**
 * 从本地法律知识库检索与查询式最相关的条目
 * @param {string} query 检索式（由法条检索型智能体生成或重写）
 * @param {number} topK 返回条数
 * @returns {Array} 命中条目，附带 score
 */
function retrieve(query, topK = 4) {
  if (!query || !String(query).trim()) return [];
  const q = String(query);
  const qBi = bigrams(q);

  const scored = ALL_KB.map((entry) => {
    let score = 0;
    // 1) 关键词命中权重最高
    for (const kw of entry.keywords) {
      if (q.includes(kw)) score += 6;
    }
    // 2) 标题片段命中
    for (const kw of entry.keywords) {
      if (entry.title.includes(kw) && q.includes(kw)) score += 2;
    }
    // 3) 字符二元组重合度（缓解同义表述漏召）
    const contentBi = bigrams(entry.title + entry.content);
    let overlap = 0;
    for (const b of qBi) {
      if (contentBi.has(b)) overlap += 1;
    }
    score += Math.min(10, overlap * 0.5);

    return { ...entry, score: Math.round(score * 100) / 100 };
  })
    .filter((e) => e.score > 2)
    .sort((a, b) => b.score - a.score)
    .slice(0, topK);

  return scored;
}

module.exports = { LEGAL_KB: ALL_KB, retrieve };
