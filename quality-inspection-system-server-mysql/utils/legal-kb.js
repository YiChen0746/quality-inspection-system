// 中文二元组切分（用于语义近似打分）
function bigrams(text) {
  const clean = String(text || '').replace(/[\s，。；：、！？,.;:!?（）()《》【】"'“”‘’\-—]/g, '');
  const set = new Set();
  for (let i = 0; i < clean.length - 1; i++) {
    set.add(clean.slice(i, i + 2));
  }
  return set;
}

